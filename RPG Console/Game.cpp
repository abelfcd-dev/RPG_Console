int GenerateRandomNumber(int min, int max)
{
    return rand() % (max - min + 1) + min;
}


Game::Game() : isRunning(false), state(GameState::Menu) {}

void Game::DisplayMap()
{
    const char* RESET = "\033[0m";
    const char* RED = "\033[31m";
    system("cls");
    for (int row = 0; row < map.size(); row++)
    {
        for (int col = 0; col < map[row].size(); col++)
        {

            if (col == position.y && row == position.x) {
                std::cout << "[H]";
            }

            else if (map[row][col]->isEnemie()) {
                std::cout << "[";
                std::cout << RED << "E";
                std::cout << RESET << "]";

            }
            else if (map[row][col]->isViking()) {
                std::cout << RED;
                std::cout << "[V]";
                std::cout << RESET;
            }
            else {
                std::cout << "[ ]";
            }

        }
        std::cout << std::endl;
    }
}

void Game::PutHeroEnemy()
{
    int rowMax = map.size();
    int colMax = map[0].size();
    int CountEnemy = rowMax * colMax * 0.05;
    int randrow = GenerateRandomNumber(0, rowMax - 1);
    int randcol = GenerateRandomNumber(0, colMax - 1);
    int posrow = -1;
    int poscol = -1;

    map[position.x][position.y]->ChangeDisco();

    while ((randrow >= position.x - 1 && randrow <= position.x + 1) && (randcol >= position.y - 1 && randcol <= position.y + 1))
    {
        randrow = GenerateRandomNumber(0, rowMax - 1);
        randcol = GenerateRandomNumber(0, colMax - 1);
    }
    map[randrow][randcol]->ChangeState("viking");

    while (CountEnemy > 0)
    {
        while (((randrow >= position.x - 1 && randrow <= position.x + 1) && (randcol >= position.y - 1 && randcol <= position.y + 1)) || map[randrow][randcol]->isEnemie() || map[randrow][randcol]->isViking())
        {
            randrow = GenerateRandomNumber(0, rowMax - 1);
            randcol = GenerateRandomNumber(0, colMax - 1);
        }
        map[randrow][randcol]->ChangeState("enemie");
        CountEnemy--;
    }

}

void Game::Move()
{
    int move = _getch();
    int posx = position.x;
    int posy = position.y;
    map[position.x][position.y]->ChangeDisco();
    switch (move)
    {
    case 'z':
        posx -= 1;
        break;
    case 'q':
        posy -= 1;
        break;
    case 's':
        posx += 1;
        break;
    case 'd':
        posy += 1;
        break;
    }

    if (posx >= map.size() || posy >= map[posx].size() || posx < 0 || posy < 0)
        return;

    position.x = posx;
    position.y = posy;
    posx = position.x;
    posy = position.y;

    map[position.x][position.y]->ChangeDisco();
}



void Game::Initialize() {
    std::cout << "=== Bienvenue dans le RPG Console ! ===\n";
    isRunning = true;
    state = GameState::Menu;
}


void Game::Loop() {
    while (isRunning) {
        switch (state) {
        case GameState::Menu:
            ShowMenu();
            break;
        case GameState::PlayGame:
            PlayGame();
            break;
        case GameState::Victory:
            Victory();
            break;
        case GameState::Defeat:
            std::cout << "Defaite...\n";
            state = GameState::Quit;
            break;
        case GameState::Quit:
            isRunning = false;
            break;
        }
    }
}
void Game::InitilizedMap(int rowCount, int colCount)
{
    map.resize(rowCount);
    for (int row = 0; row < rowCount; ++row)
    {
        map[row].resize(colCount);
        for (int col = 0; col < colCount; ++col)
        {
            map[row][col] = new Cell();
            map[row][col]->InitializeCell();
        }
    }
}

void Game::ManageGrid()
{
    DisplayMap();
    while (map[position.x][position.y]->isEnemie() == false && map[position.x][position.y]->isViking() == false)
    {
        Move();
        DisplayMap();
    }
    if (map[position.x][position.y]->isEnemie() == true)
    {
        enemie = std::make_unique<HDC>("Pierre");
        system("cls");
    }
    else
    {
        enemie = std::make_unique<Viking>("Harald");
        system("cls");
    }
}



void InitializeHero(std::unique_ptr<Hero>* player, std::vector<Item>* inventoryhero, std::string* Narme, std::string* Npotion, std::string* Nulty, int* Parme, int* Ppotion, int* Pulty)
{
    std::string hero;
    std::cout << "\nQuel nom pour ton heros ?\n";
    std::cin >> hero;
    *player = std::make_unique<Hero>(hero);

    *Narme = "Epee en bois";
    *Npotion = "Potion Soin";
    *Nulty = "Boule de feu";
    *Parme = 5;
    *Ppotion = 10;
    *Pulty = 10;
}


void Game::ShowMenu() {
    int rowCount = 17;
    int colCount = 27;
    InitilizedMap(rowCount, colCount);
    PutHeroEnemy();
    InitializeHero(&player, &inventoryhero, &Narme, &Npotion, &Nulty, &Parme, &Ppotion, &Pulty);
    state = GameState::PlayGame;
}


void Game::PlayGame() {
    ManageGrid();

    inventoryhero.push_back(Item(Narme, Parme));
    inventoryhero.push_back(Item(Nulty, Pulty));
    inventoryhero.push_back(Item(Npotion, Ppotion));

    std::cout << "\n=== Combats contre " << enemie->GetName() << " === \n";
    std::cout << "Lancer le combat\n\n";
    system("pause");

    int turn = 1;
    std::cout << "\nLe combat commence entre " << player->GetName()
        << " et " << enemie->GetName() << " !\n";

    while (!player->IsDead() && !enemie->IsDead()) {
        system("cls");
        std::cout << "\n===== TOUR " << turn++ << " =====\n";

        player->DisplayChar();
        enemie->DisplayChar();
        player->DisplayItem(inventoryhero);
        int choiceitem = 0;
        std::cout << "Quel objet veux tu utiliser ?\n";
        std::cin >> choiceitem;
        player->AttackItem(inventoryhero, choiceitem, *enemie);
        switch (choiceitem)
        {
        case 2:
            inventoryhero.erase(inventoryhero.begin() + 1);
            break;
        case 3:
            inventoryhero.erase(inventoryhero.begin() + 2);
            break;
        }

        if (enemie->IsDead()) {
            std::cout << enemie->GetName() << " est vaincu !\n";
            state = GameState::Victory;
            return;
        }

        std::cout << "Au tour son tour d'attaquer !! \n";
        std::this_thread::sleep_for(std::chrono::seconds(2));

        enemie->Attack(*player);

        if (player->IsDead()) {
            std::cout << player->GetName() << " est tombe au combat...\n";
            state = GameState::Defeat;
            return;
        }
    }
}


